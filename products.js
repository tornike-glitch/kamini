// --- CLOUD STORAGE STATE MANAGER ---
const CloudStorageManager = {
  priceMap: {},

  async init() {
    this.loadLocalCache();
    await this.syncFromCloud();
  },

  loadLocalCache() {
    try {
      const cached = localStorage.getItem(CLOUD_CONFIG.storageKey);
      if (cached) {
        this.priceMap = JSON.parse(cached);
        this.applyPricesToProducts();
      }
    } catch (e) {
      console.warn("Local price cache read error:", e);
    }
  },

  async syncFromCloud() {
    try {
      const response = await fetch(CLOUD_CONFIG.endpoint, {
        method: "GET",
        headers: { "X-Master-Key": CLOUD_CONFIG.apiKey }
      });
      if (response.ok) {
        const data = await response.json();
        const cloudData = data.record || data;
        if (cloudData && typeof cloudData === "object") {
          this.priceMap = cloudData;
          localStorage.setItem(CLOUD_CONFIG.storageKey, JSON.stringify(this.priceMap));
          this.applyPricesToProducts();
          window.dispatchEvent(new CustomEvent("gmt:prices-updated"));
          return true;
        }
      }
    } catch (e) {
      console.info("Cloud storage sync note:", e);
    }
    return false;
  },

  async savePricesToCloud(newPriceMap) {
    this.priceMap = { ...this.priceMap, ...newPriceMap };
    localStorage.setItem(CLOUD_CONFIG.storageKey, JSON.stringify(this.priceMap));
    this.applyPricesToProducts();

    try {
      const response = await fetch(CLOUD_CONFIG.endpoint, {
        method: "PUT",
        headers: {
          "Content-Type": "application/json",
          "X-Master-Key": CLOUD_CONFIG.apiKey
        },
        body: JSON.stringify(this.priceMap)
      });
      if (response.ok) {
        window.dispatchEvent(new CustomEvent("gmt:prices-updated"));
        return { success: true, message: "Cloud storage updated successfully!" };
      }
    } catch (e) {
      console.error("Cloud save error:", e);
    }
    window.dispatchEvent(new CustomEvent("gmt:prices-updated"));
    return { success: true, message: "Saved locally." };
  },

  applyPricesToProducts() {
    PRODUCTS.forEach(product => {
      const stored = this.priceMap[product.id];
      if (stored) {
        if (stored.gel !== undefined && stored.gel !== null && stored.gel !== "") product.priceGel = Number(stored.gel);
        if (stored.eur !== undefined && stored.eur !== null && stored.eur !== "") product.priceEur = Number(stored.eur);
        if (stored.pln !== undefined && stored.pln !== null && stored.pln !== "") product.pricePln = Number(stored.pln);
      }
    });
  },

  getPriceForCurrency(product, currency = "GEL") {
    const cur = (currency || "GEL").toUpperCase();
    if (cur === "GEL" && product.priceGel) return { amount: product.priceGel, symbol: "GEL", code: "GEL" };
    if (cur === "EUR" && product.priceEur) return { amount: product.priceEur, symbol: "EUR", code: "EUR" };
    if (cur === "PLN" && product.pricePln) return { amount: product.pricePln, symbol: "PLN", code: "PLN" };
    
    if (product.priceGel) {
      if (cur === "EUR") return { amount: Math.round(product.priceGel / 2.95), symbol: "EUR", code: "EUR" };
      if (cur === "PLN") return { amount: Math.round(product.priceGel * 1.45), symbol: "PLN", code: "PLN" };
      return { amount: product.priceGel, symbol: "GEL", code: "GEL" };
    }
    if (product.priceEur) {
      if (cur === "GEL") return { amount: Math.round(product.priceEur * 2.95), symbol: "GEL", code: "GEL" };
      if (cur === "PLN") return { amount: Math.round(product.priceEur * 4.3), symbol: "PLN", code: "PLN" };
      return { amount: product.priceEur, symbol: "EUR", code: "EUR" };
    }
    if (product.pricePln) {
      if (cur === "GEL") return { amount: Math.round(product.pricePln / 1.45), symbol: "GEL", code: "GEL" };
      if (cur === "EUR") return { amount: Math.round(product.pricePln / 4.3), symbol: "EUR", code: "EUR" };
      return { amount: product.pricePln, symbol: "PLN", code: "PLN" };
    }

    return null;
  }
};

CloudStorageManager.init();